class SiteError(Exception):
    def __init__(self, status: int, message: str):
        super().__init__(message)
        self.status, self.message = status, message


def check_site_name(name: str) -> str:
    if not isinstance(name, str) or not SITE_NAME_RE.match(name):
        raise SiteError(400, "site name: 1-40 characters, lowercase letters, digits and '-', "
                             "starting with a letter or digit")
    return name


def clean_path(path: str) -> str:
    """A file path relative to the site root. Rejects absolute paths, '..', '.', empty parts,
    backslashes and control characters."""
    if not isinstance(path, str) or not path or len(path) > 255 or _BAD_CHARS.search(path):
        raise SiteError(400, "path must be a relative path (max 255 chars, no backslashes or "
                             "control characters)")
    if path.startswith("/"):
        raise SiteError(400, "path must be relative to the site root, not absolute")
    parts = path.split("/")
    if any(p in ("", ".", "..") for p in parts):
        raise SiteError(400, "path may not contain '..', '.' or empty segments")
    if len(parts) > 10:
        raise SiteError(400, "path is nested too deeply (max 10 levels)")
    return str(PurePosixPath(*parts))


