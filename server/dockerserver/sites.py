class SiteFiles:
    """The sites' files on local disk."""

    def __init__(self, root: Path):
        self.root = root

    def site_dir(self, user_id: int, name: str) -> Path:
        return self.root / f"u{int(user_id)}" / check_site_name(name)

    def _mkdir(self, d: Path):
        d.mkdir(parents=True, exist_ok=True)
        os.chmod(d, 0o755)   # the nginx container (uid 101) must be able to list it

    def write(self, user_id: int, name: str, path: str, data: bytes) -> None:
        base = self.site_dir(user_id, name)
        rel = clean_path(path)
        target = base / rel
        # belt and braces: the resolved target must stay inside the site directory
        if not target.resolve().is_relative_to(base.resolve()):
            raise SiteError(400, "path escapes the site directory")
        self._mkdir(self.root)
        self._mkdir(self.root / f"u{int(user_id)}")
        self._mkdir(base)
        d = base
        for part in PurePosixPath(rel).parts[:-1]:
            d = d / part
            if d.is_symlink() or (d.exists() and not d.is_dir()):
                raise SiteError(409, f"'{part}' already exists as a file")
            self._mkdir(d)
        if target.is_dir():
            raise SiteError(409, "a directory with that path already exists")
        tmp = target.with_name(f".{target.name}.upload")
        with open(tmp, "wb") as f:
            f.write(data)
        os.chmod(tmp, 0o644)
        os.replace(tmp, target)

    def delete_file(self, user_id: int, name: str, path: str) -> bool:
        target = self.site_dir(user_id, name) / clean_path(path)
        if target.is_file() and not target.is_symlink():
            target.unlink()
            return True
        return False

    def file_size(self, user_id: int, name: str, path: str) -> int:
        target = self.site_dir(user_id, name) / clean_path(path)
        return target.stat().st_size if target.is_file() else 0

    def list(self, user_id: int, name: str) -> list[dict]:
        base = self.site_dir(user_id, name)
        out = []
        if not base.is_dir():
            return out
        for dirpath, dirnames, filenames in os.walk(base):
            dirnames.sort()
            for fn in sorted(filenames):
                if fn.startswith(".") and fn.endswith(".upload"):
                    continue
                p = Path(dirpath) / fn
                st = p.stat()
                out.append({"path": p.relative_to(base).as_posix(), "size": st.st_size,
                            "modified": datetime.fromtimestamp(int(st.st_mtime), timezone.utc).replace(tzinfo=None)})
        return out

    def usage(self, user_id: int, name: str) -> tuple[int, int]:
        files = self.list(user_id, name)
        return len(files), sum(f["size"] for f in files)

    def remove(self, user_id: int, name: str):
        shutil.rmtree(self.site_dir(user_id, name), ignore_errors=True)

    def remove_user(self, user_id: int):
        shutil.rmtree(self.root / f"u{int(user_id)}", ignore_errors=True)


