class SiteManager:
    """Wake / sleep bookkeeping. Blocking methods; the async proxy calls them in a thread."""

    def __init__(self, settings, session_factory, runtime=None):
        self.settings, self.Session = settings, session_factory
        self.files = SiteFiles(settings.sites_dir)
        self.runtime = runtime if runtime is not None else DockerSiteRuntime(settings)
        self._locks: dict[int, threading.Lock] = {}
        self._locks_guard = threading.Lock()
        self._addr: dict[int, str] = {}
        # unsaved counters: site_id -> [requests, bytes, last_access]
        self._pending: dict[int, list] = {}
        self._pending_lock = threading.Lock()
        self._stop = threading.Event()
        self._thread: threading.Thread | None = None

    def _lock(self, site_id: int) -> threading.Lock:
        with self._locks_guard:
            return self._locks.setdefault(site_id, threading.Lock())

    # ----- request path -----
    def record(self, site_id: int, nbytes: int):
        with self._pending_lock:
            p = self._pending.setdefault(site_id, [0, 0, None])
            p[0] += 1
            p[1] += nbytes
            p[2] = utcnow()

    def last_access(self, site: Site) -> datetime | None:
        with self._pending_lock:
            p = self._pending.get(site.id)
        cands = [t for t in (p[2] if p else None, site.last_access_at, site.awake_since) if t]
        return max(cands) if cands else None

    def ensure_awake(self, site_id: int) -> str:
        """Address ('ip:port') of the site's running container, starting it if needed."""
        addr = self._addr.get(site_id)
        if addr:
            return addr
        self._make_room(site_id)
        with self._lock(site_id):
            with self.Session() as db:
                site = db.get(Site, site_id)
                if site is None:
                    raise SiteError(404, "site not found")
                if site.container_id:
                    addr = self.runtime.address(site.container_id)
                    if addr and wait_ready(addr, 2):
                        self._addr[site_id] = addr
                        return addr
                    self._finish_awake(db, site)   # container vanished: close its awake period
                site_dir = self.files.site_dir(site.user_id, site.name)
                if not site_dir.is_dir():
                    raise SiteError(404, "site has no files")
                cid, addr = self.runtime.start(site.id, site.user_id, site_dir)
                if not wait_ready(addr, 5):
                    self.runtime.stop(cid)
                    raise SiteError(503, "site did not start in time")
                site.container_id, site.awake_since = cid, utcnow()
                site.wake_count += 1
                db.commit()
                self._addr[site_id] = addr
                log.info("site %s woke up (%s)", site_id, addr)
                return addr

    def forget(self, site_id: int):
        """The cached address stopped answering (container died); next ensure_awake re-checks."""
        self._addr.pop(site_id, None)

    def _make_room(self, waking_id: int):
        cap = self.settings.site_max_awake
        if cap <= 0:
            return
        with self.Session() as db:
            awake = db.scalars(select(Site).where(Site.container_id.is_not(None),
                                                  Site.id != waking_id)).all()
            if len(awake) < cap:
                return
            awake.sort(key=lambda s: self.last_access(s) or datetime.min)
            victims = [s.id for s in awake[:len(awake) - cap + 1]]
        for sid in victims:
            self.sleep(sid, "too many awake sites")

    # ----- sleeping -----
    def _finish_awake(self, db, site: Site, now: datetime | None = None):
        """Close the current awake period: add it to the usage, charge it, clear the container."""
        now = now or utcnow()
        if site.awake_since:
            secs = max((now - site.awake_since).total_seconds(), 0.0)
            site.awake_seconds = (site.awake_seconds or 0.0) + secs
            rate = self.settings.site_credit_per_hour
            if rate > 0 and secs > 0:
                c = cost_uh(rate, 0, secs)
                if c:
                    site.cost_uh = (site.cost_uh or 0) + c
                    add_entry(db, site.user_id, -c, "site",
                              note=f"site {site.name}: {round(secs)} s awake")
        site.container_id, site.awake_since = None, None
        self._addr.pop(site.id, None)

    def sleep(self, site_id: int, reason: str = "idle"):
        with self._lock(site_id):
            self.flush()
            with self.Session() as db:
                site = db.get(Site, site_id)
                if site is None or not site.container_id:
                    self._addr.pop(site_id, None)
                    return
                try:
                    self.runtime.stop(site.container_id)
                except Exception as e:   # keep the bookkeeping right even if Docker hiccups
                    log.warning("stopping site %s container failed: %s", site_id, e)
                self._finish_awake(db, site)
                db.commit()
                log.info("site %s went to sleep (%s)", site_id, reason)

    # ----- periodic work -----
    def flush(self):
        """Write the request counters to the database."""
        with self._pending_lock:
            pending, self._pending = self._pending, {}
        if not pending:
            return
        with self.Session() as db:
            for sid, (n, b, last) in pending.items():
                db.execute(update(Site).where(Site.id == sid).values(
                    requests=Site.requests + n, bytes_served=Site.bytes_served + b,
                    last_access_at=last))
            db.commit()

    def tick(self):
        self.flush()
        idle = timedelta(seconds=self.settings.site_idle_seconds)
        now = utcnow()
        with self.Session() as db:
            awake = db.scalars(select(Site).where(Site.container_id.is_not(None))).all()
            sleepy = [s.id for s in awake if now - (self.last_access(s) or now) >= idle]
        for sid in sleepy:
            self.sleep(sid, "idle")

    def recover(self):
        """At startup: adopt containers of known sites, remove strays, and close awake periods
        of containers that disappeared while the server was down."""
        try:
            containers = self.runtime.list()
        except Exception as e:
            log.warning("sites: Docker not reachable (%s); site containers not checked", e)
            return
        with self.Session() as db:
            known = {s.container_id: s for s in db.scalars(
                select(Site).where(Site.container_id.is_not(None)))}
            alive = set()
            for cid, sid in containers:
                s = known.get(cid)
                if s is not None and s.id == sid and self.runtime.address(cid):
                    alive.add(cid)
                else:
                    self.runtime.stop(cid)
            for cid, s in known.items():
                if cid not in alive:
                    self._finish_awake(db, s, now=s.last_access_at or s.awake_since)
            db.commit()

    def start(self):
        if self._thread is not None:
            return

        def loop():
            while not self._stop.wait(self.settings.site_reap_interval):
                try:
                    self.tick()
                except Exception:
                    log.exception("site reaper failed")
        self._thread = threading.Thread(target=loop, name="site-reaper", daemon=True)
        self._thread.start()

    def shutdown(self):
        self._stop.set()
        try:
            self.flush()
        except Exception:
            log.exception("site counters flush failed")
