from .models import Site, utcnow

log = logging.getLogger("dockerserver.sites")

SITE_NAME_RE = re.compile(r"^[a-z0-9][a-z0-9-]{0,39}$")
_BAD_CHARS = re.compile(r"[\x00-\x1f\x7f\\]")
SITE_PORT = 8080
CONTAINER_PREFIX = "fc-site-"

