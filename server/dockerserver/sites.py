class DockerSiteRuntime:
    """Starts / stops the per-site nginx containers on this host's Docker."""

    def __init__(self, settings, client=None):
        self.settings = settings
        self._client = client
        self._net_ready = False
        self._lock = threading.Lock()

    @property
    def client(self):
        if self._client is None:
            import docker
            self._client = docker.from_env()
        return self._client

    @property
    def conf_path(self) -> Path:
        return self.settings.sites_dir / "nginx.conf"

    def _prepare(self):
        with self._lock:
            if self._net_ready:
                return
            st = self.settings
            st.sites_dir.mkdir(parents=True, exist_ok=True)
            os.chmod(st.sites_dir, 0o755)
            if not self.conf_path.exists() or self.conf_path.read_text() != NGINX_CONF:
                self.conf_path.write_text(NGINX_CONF)
                os.chmod(self.conf_path, 0o644)
            nets = self.client.networks.list(names=[st.site_network])
            if not [n for n in nets if n.name == st.site_network]:
                # internal: no route to the internet or the LAN; icc off: sites can't reach
                # each other. The host can still reach them (that's how the proxy connects).
                self.client.networks.create(
                    st.site_network, driver="bridge", internal=True,
                    options={"com.docker.network.bridge.enable_icc": "false"},
                    labels={"fc.kind": "site-network"})
            self._net_ready = True

    def start(self, site_id: int, user_id: int, site_dir: Path) -> tuple[str, str]:
        """Create and start the container; returns (container_id, 'ip:port')."""
        import docker
        from docker.types import LogConfig, Mount
        self._prepare()
        st = self.settings
        name = f"{CONTAINER_PREFIX}{site_id}"
        try:
            self.client.containers.get(name).remove(force=True)
        except docker.errors.NotFound:
            pass
        kwargs = dict(
            entrypoint=["nginx"], command=["-c", "/etc/fc-site/nginx.conf", "-g", "daemon off;"],
            name=name, detach=True, user="101:101", read_only=True,
            tmpfs={"/tmp": "size=8m,mode=1777"}, cap_drop=["ALL"],
            security_opt=["no-new-privileges"], mem_limit="32m", memswap_limit="32m",
            nano_cpus=250_000_000, pids_limit=32, network=st.site_network,
            labels={"fc.kind": "site", "fc.site_id": str(site_id), "fc.user_id": str(user_id)},
            mounts=[Mount("/srv", str(site_dir), type="bind", read_only=True),
                    Mount("/etc/fc-site/nginx.conf", str(self.conf_path), type="bind", read_only=True)],
            log_config=LogConfig(type="json-file", config={"max-size": "1m", "max-file": "1"}))
        try:
            c = self.client.containers.run(st.site_image, **kwargs)
        except docker.errors.ImageNotFound:
            log.warning("pulling site image %s", st.site_image)
            self.client.images.pull(st.site_image)
            c = self.client.containers.run(st.site_image, **kwargs)
        addr = self.address(c.id)
        if addr is None:
            raise SiteError(503, "site container did not start")
        return c.id, addr

    def address(self, container_id: str) -> str | None:
        import docker
        try:
            c = self.client.containers.get(container_id)
        except docker.errors.NotFound:
            return None
        if c.status != "running":
            return None
        ip = (c.attrs.get("NetworkSettings", {}).get("Networks", {})
              .get(self.settings.site_network, {}).get("IPAddress"))
        return f"{ip}:{SITE_PORT}" if ip else None

    def stop(self, container_id: str):
        import docker
        try:
            self.client.containers.get(container_id).remove(force=True)
        except docker.errors.NotFound:
            pass

    def list(self) -> list[tuple[str, int]]:
        """(container_id, site_id) of every site container on this host."""
        out = []
        for c in self.client.containers.list(all=True, filters={"label": "fc.kind=site"}):
            try:
                out.append((c.id, int(c.labels.get("fc.site_id", "0"))))
            except ValueError:
                out.append((c.id, 0))
        return out

    def stats(self, container_id: str) -> dict | None:
        """Current memory use of an awake container (MB), or None."""
        try:
            s = self.client.containers.get(container_id).stats(stream=False)
            return {"mem_mb": round(s.get("memory_stats", {}).get("usage", 0) / 2**20, 1)}
        except Exception:
            return None


def wait_ready(addr: str, timeout: float = 5.0) -> bool:
    host, port = addr.rsplit(":", 1)
    end = time.monotonic() + timeout
    while time.monotonic() < end:
        try:
            with socket.create_connection((host, int(port)), timeout=0.5):
                return True
        except OSError:
            time.sleep(0.05)
    return False


