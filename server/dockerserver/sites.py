"""Static web sites: per-user persistent files, served by a small nginx container per site.

Layout
  files      <data_dir>/sites/u<user_id>/<site>/...   (on the bridge's disk; survive everything
             except delete_site / deleting the user)
  container  fc-site-<site_id>: nginx:alpine, read-only root, uid 101, no capabilities, 32 MB,
             0.25 CPU, the site directory mounted read-only at /srv, on the internal Docker
             network fc-sites (no internet, containers cannot reach each other).
  public URL <SITES_URL>/sites/<user>/<site>/  -> Caddy -> DockerServer (proxy below) -> nginx

Sleep / wake: a site's container is started by the first request for it and stopped after
SITE_IDLE_SECONDS (default 1 h) without requests; the next request starts it again (well under
a second). At most SITE_MAX_AWAKE containers are awake at once (least recently used ones are
stopped first). Usage per site (requests, bytes served, awake time, wake-ups, stored bytes) is
recorded; awake time is charged at SITE_CREDIT_PER_HOUR credit-hours per hour (default 0).

Sites only serve files. Nothing a user uploads is ever executed on the server.
"""
import logging
import os
import re
import shutil
import socket
import threading
import time
from datetime import datetime, timedelta, timezone
from pathlib import Path, PurePosixPath

from sqlalchemy import select, update

